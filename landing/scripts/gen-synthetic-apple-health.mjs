#!/usr/bin/env node
/**
 * SYNTHETIC Apple Health export generator (task 082 B2) — FAKE DATA ONLY, for testing
 * /connect/apple-health/file. Mirrors Apple's export.xml structure (inline DTD, HealthData root,
 * <Record> attributes, HRV metadata list, iOS 16+ sleep stages + older InBed/Asleep, several sources).
 *
 *   node scripts/gen-synthetic-apple-health.mjs <out.xml|out.zip> [--days 240] [--pad-mb 0] [--seed 1]
 *
 * --sleep-var H spreads wake time by ±H hours (wide sleep range).
 * --pad-mb N adds StepCount filler records until the XML is ≈N MB (memory/large-file test).
 * A .zip output is written with fflate's streaming Zip (data descriptors, like many real archives),
 * with the XML at apple_health_export/export.xml plus a dummy export_cda.xml after it.
 */
import { createWriteStream } from 'node:fs'
import { Zip, ZipDeflate } from 'fflate'

const args = process.argv.slice(2)
const out = args[0]
if (!out) {
  console.error('usage: gen-synthetic-apple-health.mjs <out.xml|out.zip> [--days N] [--pad-mb N] [--seed N]')
  process.exit(1)
}
const opt = (k, d) => {
  const i = args.indexOf(k)
  return i > 0 ? Number(args[i + 1]) : d
}
const DAYS = opt('--days', 240)
const PAD_MB = opt('--pad-mb', 0)
const SLEEP_VAR = opt('--sleep-var', 0) // extra ± hours of night-to-night sleep spread (tests the wide-range note)
let seed = opt('--seed', 1)
const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647)
const gauss = () => Math.sqrt(-2 * Math.log(rnd() + 1e-12)) * Math.cos(2 * Math.PI * rnd())

const pad = (n) => String(n).padStart(2, '0')
const TZ = '+0200'
const fmt = (ms) => {
  const d = new Date(ms + 2 * 3600e3)
  return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}:${pad(d.getUTCSeconds())} ${TZ}`
}

const WATCH_DEV = '&lt;&lt;HKDevice: 0x600000000000&gt;, name:Apple Watch, manufacturer:Apple Inc., model:Watch, hardware:Watch7,1, software:11.0&gt;'
const PHONE_DEV = '&lt;&lt;HKDevice: 0x600000000001&gt;, name:iPhone, manufacturer:Apple Inc., model:iPhone, hardware:iPhone15,2, software:18.0&gt;'
const WATCH = 'Synthetic Test Watch'
const PHONE = 'Synthetic Test iPhone'

const HEADER = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE HealthData [
<!-- SYNTHETIC TEST FILE — fake data generated by gen-synthetic-apple-health.mjs -->
<!ELEMENT HealthData (ExportDate,Me,(Record|Correlation|Workout|ActivitySummary|ClinicalRecord|Audiogram|VisionPrescription)*)>
<!ATTLIST HealthData
  locale CDATA #REQUIRED
>
<!ELEMENT ExportDate EMPTY>
<!ATTLIST ExportDate
  value CDATA #REQUIRED
>
<!ELEMENT Me EMPTY>
<!ATTLIST Me
  HKCharacteristicTypeIdentifierDateOfBirth         CDATA #REQUIRED
  HKCharacteristicTypeIdentifierBiologicalSex       CDATA #REQUIRED
>
<!ELEMENT Record ((MetadataEntry|HeartRateVariabilityMetadataList)*)>
<!ATTLIST Record
  type          CDATA #REQUIRED
  unit          CDATA #IMPLIED
  value         CDATA #IMPLIED
  sourceName    CDATA #REQUIRED
  sourceVersion CDATA #IMPLIED
  device        CDATA #IMPLIED
  creationDate  CDATA #IMPLIED
  startDate     CDATA #REQUIRED
  endDate       CDATA #REQUIRED
>
<!ELEMENT MetadataEntry EMPTY>
<!ATTLIST MetadataEntry
  key   CDATA #REQUIRED
  value CDATA #REQUIRED
>
<!ELEMENT HeartRateVariabilityMetadataList (InstantaneousBeatsPerMinute*)>
<!ELEMENT InstantaneousBeatsPerMinute EMPTY>
<!ATTLIST InstantaneousBeatsPerMinute
  bpm  CDATA #REQUIRED
  time CDATA #REQUIRED
>
]>
<HealthData locale="en_US">
 <ExportDate value="${fmt(Date.UTC(2026, 9, 10, 8))}"/>
 <Me HKCharacteristicTypeIdentifierDateOfBirth="" HKCharacteristicTypeIdentifierBiologicalSex="HKBiologicalSexNotSet"/>
`

function rec(type, src, dev, unit, value, s, e, inner = '') {
  const d = dev ? ` device="${dev}"` : ''
  const u = unit ? ` unit="${unit}"` : ''
  const head = ` <Record type="${type}" sourceName="${src}" sourceVersion="1.0"${d}${u} creationDate="${fmt(e)}" startDate="${fmt(s)}" endDate="${fmt(e)}" value="${value}"`
  return inner ? `${head}>\n${inner} </Record>\n` : `${head}/>\n`
}

function* records() {
  const end = Date.UTC(2026, 9, 10, 0) - 2 * 3600e3 // local midnight 2026-10-10
  const stagesFrom = end - Math.floor(DAYS * 0.4) * 86400e3 // older part uses pre-iOS-16 values
  for (let i = DAYS; i >= 1; i--) {
    const day0 = end - i * 86400e3
    const dip = i <= 5 ? -14 : 0 // a recent low spell, to exercise "days outside your range"
    // HRV SDNN — daytime samples from the watch (with the beat-to-beat metadata list)
    const n = 3 + Math.floor(rnd() * 5)
    for (let k = 0; k < n; k++) {
      const s = day0 + (7 + rnd() * 15) * 3600e3
      const v = Math.max(8, 46 + dip + gauss() * 9).toFixed(4)
      const inner = `  <HeartRateVariabilityMetadataList>\n   <InstantaneousBeatsPerMinute bpm="61" time="9:11:47.12 AM"/>\n   <InstantaneousBeatsPerMinute bpm="63" time="9:11:48.07 AM"/>\n  </HeartRateVariabilityMetadataList>\n`
      yield rec('HKQuantityTypeIdentifierHeartRateVariabilitySDNN', WATCH, WATCH_DEV, 'ms', v, s, s + 60e3, inner)
    }
    // Resting HR — one per day
    yield rec('HKQuantityTypeIdentifierRestingHeartRate', WATCH, WATCH_DEV, 'count/min', Math.round(55 - dip / 3 + gauss() * 2), day0 + 3600e3, day0 + 23 * 3600e3)
    // Other sources writing into Apple Health
    if (i % 2 === 0) yield rec('HKQuantityTypeIdentifierHeartRateVariabilitySDNN', 'Oura', '', 'ms', (38 + gauss() * 6).toFixed(1), day0 + 3 * 3600e3, day0 + 3 * 3600e3 + 300e3)
    if (i % 3 === 0) yield rec('HKQuantityTypeIdentifierRestingHeartRate', 'WHOOP', '', 'count/min', Math.round(52 + gauss() * 2), day0 + 2 * 3600e3, day0 + 6 * 3600e3)
    if (i % 4 === 0) yield rec('HKQuantityTypeIdentifierHeartRateVariabilitySDNN', 'Ultrahuman', '', 'ms', (41 + gauss() * 5).toFixed(1), day0 + 4 * 3600e3, day0 + 4 * 3600e3 + 300e3)
    if (i % 5 === 0) yield rec('HKQuantityTypeIdentifierHeartRateVariabilitySDNN', 'ONDA', '', 'ms', (50 + gauss() * 8).toFixed(1), day0 + 18 * 3600e3, day0 + 18 * 3600e3 + 120e3)
    // Sleep: night ending on this day
    const bed = day0 - (1.2 + rnd()) * 3600e3
    const wake = day0 + (6 + rnd() * 1.5 + (rnd() * 2 - 1) * SLEEP_VAR) * 3600e3 + (dip ? -3600e3 : 0)
    yield rec('HKCategoryTypeIdentifierSleepAnalysis', PHONE, PHONE_DEV, '', 'HKCategoryValueSleepAnalysisInBed', bed, wake)
    if (day0 < stagesFrom) {
      yield rec('HKCategoryTypeIdentifierSleepAnalysis', WATCH, WATCH_DEV, '', 'HKCategoryValueSleepAnalysisAsleep', bed + 15 * 60e3, wake - 10 * 60e3)
    } else {
      const seq = ['AsleepCore', 'AsleepDeep', 'AsleepCore', 'AsleepREM', 'Awake', 'AsleepCore', 'AsleepREM']
      let t = bed + 12 * 60e3
      const step = (wake - t) / seq.length
      for (const st of seq) {
        yield rec('HKCategoryTypeIdentifierSleepAnalysis', WATCH, WATCH_DEV, '', `HKCategoryValueSleepAnalysis${st}`, t, t + step)
        t += step
      }
    }
    // A few filler types the parser must skip
    yield rec('HKQuantityTypeIdentifierStepCount', PHONE, PHONE_DEV, 'count', Math.round(rnd() * 900), day0 + 10 * 3600e3, day0 + 10.2 * 3600e3)
    yield rec('HKQuantityTypeIdentifierHeartRate', WATCH, WATCH_DEV, 'count/min', Math.round(70 + gauss() * 8), day0 + 12 * 3600e3, day0 + 12 * 3600e3)
  }
}

const enc = new TextEncoder()
async function main() {
  const isZip = out.endsWith('.zip')
  const ws = createWriteStream(out)
  const write = (buf) => new Promise((res) => (ws.write(buf) ? res() : ws.once('drain', res)))
  let zip, entry
  let pending = Promise.resolve()
  if (isZip) {
    zip = new Zip((err, data) => {
      if (err) throw err
      const b = Buffer.from(data)
      pending = pending.then(() => write(b))
    })
    entry = new ZipDeflate('apple_health_export/export.xml', { level: 6 })
    zip.add(entry)
  }
  let bytes = 0
  let buf = ''
  const emit = async (s, final = false) => {
    buf += s
    if (buf.length > 1 << 20 || final) {
      const b = enc.encode(buf)
      bytes += b.length
      buf = ''
      if (isZip) {
        entry.push(b, final)
        await pending
      } else await write(b)
    }
  }
  await emit(HEADER)
  for (const r of records()) await emit(r)
  const target = PAD_MB * 1024 * 1024
  let t = Date.UTC(2020, 0, 1)
  while (bytes + buf.length < target) {
    await emit(rec('HKQuantityTypeIdentifierStepCount', PHONE, PHONE_DEV, 'count', Math.round(rnd() * 300), t, t + 60e3))
    t += 61e3
  }
  await emit('</HealthData>\n', true)
  if (isZip) {
    const cda = new ZipDeflate('apple_health_export/export_cda.xml', { level: 6 })
    zip.add(cda)
    cda.push(enc.encode('<?xml version="1.0"?><ClinicalDocument>SYNTHETIC</ClinicalDocument>'), true)
    zip.end()
    await pending
  }
  ws.end()
  await new Promise((r) => ws.on('finish', r))
  console.log(`wrote ${out}: XML ${(bytes / 1048576).toFixed(1)} MB`)
}
main()
