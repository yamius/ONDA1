export type HrvVerdict = 'lower' | 'middle' | 'higher'

/** Sex choice in the UI: 'unspecified' ("prefer not to say") shows the comparison with BOTH groups, no single verdict. */
export type HrvSexChoice = HrvSex | 'unspecified'

