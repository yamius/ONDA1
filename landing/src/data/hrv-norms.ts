export interface HrvResult {
  /** Nearest age point in the table (no interpolation). */
  point: HrvAgePoint
  sex: HrvSex
  ref: HrvQuartiles
  verdict: HrvVerdict
  /** True when the age is outside 20–61, so the nearest point is the edge of the data. */
  outsideAgeRange: boolean
}

/** Nearest age point by distance to its two-year span; a tie goes to the younger point. */
export function nearestAgePoint(age: number): HrvAgePoint {
  let best = HRV_AGE_POINTS[0]
  let bestD = Infinity
  for (const p of HRV_AGE_POINTS) {
    const d = age < p.minAge ? p.minAge - age : age > p.maxAge ? age - p.maxAge : 0
    if (d < bestD) {
      best = p
      bestD = d
    }
  }
  return best
}

export function interpretHrv(age: number, rmssd: number, sex: HrvSex): HrvResult {
  const point = nearestAgePoint(age)
  const ref = point[sex]
  const verdict: HrvVerdict = rmssd < ref.p25 ? 'lower' : rmssd > ref.p75 ? 'higher' : 'middle'
  const first = HRV_AGE_POINTS[0]
  const last = HRV_AGE_POINTS[HRV_AGE_POINTS.length - 1]
  return { point, sex, ref, verdict, outsideAgeRange: age < first.minAge || age > last.maxAge }
}

/** Template values for copy that quotes the table ({{f20}}, {{m40}} …: medians at 20–21, 40–41, 60–61). */
export const HRV_COPY_VARS: Record<string, number> = Object.fromEntries(
  HRV_AGE_POINTS.flatMap((p) => [
    [`f${p.minAge}`, p.female.p50],
    [`m${p.minAge}`, p.male.p50],
  ]),
)

/** Comparison with both groups at the nearest age point (sex not given): no single verdict. */
export function interpretHrvBoth(age: number, rmssd: number): Record<HrvSex, HrvResult> {
  return { female: interpretHrv(age, rmssd, 'female'), male: interpretHrv(age, rmssd, 'male') }
}
